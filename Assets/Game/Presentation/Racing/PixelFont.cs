using System.Collections.Generic;
using UnityEngine;

namespace Game.Presentation.Racing
{
    /// <summary>DEV-022: an original 5 × 7 dot-matrix font for hologram signs, drawn one shader dot per glyph pixel (the track's
    /// "pixel perfect pixelated" look). Upper case, digits, common punctuation and arrows (→ ← ↑ ↓); lower case is drawn as upper
    /// case and unknown characters as a blank. Monospace: each glyph is 5 pixels wide plus a 1-pixel gap; a line is 9 pixels.</summary>
    public static class PixelFont
    {
        public const int Width = 5, Height = 7, Advance = 6, LineHeight = 9;

        [Game.Core.StaticStateOk("constant glyph table, built once")]
        static readonly Dictionary<char, byte[]> Glyphs = Build();

        /// <summary>The rows of a glyph top to bottom; bit 4 is the leftmost pixel. Null for a blank.</summary>
        public static byte[] Rows(char c)
        {
            if (c >= 'a' && c <= 'z') c = (char)(c - 32);
            return Glyphs.TryGetValue(c, out var rows) ? rows : null;
        }

        /// <summary>Size in pixels of a block of text (lines split on '\n').</summary>
        public static Vector2Int Measure(string text)
        {
            int lines = 1, longest = 0, run = 0;
            foreach (char c in text)
            {
                if (c == '\n') { lines++; run = 0; continue; }
                run++; longest = Mathf.Max(longest, run);
            }
            return new Vector2Int(longest == 0 ? 0 : longest * Advance - 1, lines * LineHeight - 2);
        }

        public static int LineWidth(string line) => line.Length == 0 ? 0 : line.Length * Advance - 1;

        static Dictionary<char, byte[]> Build()
        {
            var d = new Dictionary<char, byte[]>();
            void G(char c, string rows)
            {
                var parts = rows.Split(' ');
                var bits = new byte[Height];
                for (int y = 0; y < Height; y++)
                    for (int x = 0; x < Width; x++)
                        if (parts[y][x] == '#') bits[y] |= (byte)(1 << (Width - 1 - x));
                d[c] = bits;
            }
            G('A', ".###. #...# #...# ##### #...# #...# #...#");
            G('B', "####. #...# #...# ####. #...# #...# ####.");
            G('C', ".###. #...# #.... #.... #.... #...# .###.");
            G('D', "####. #...# #...# #...# #...# #...# ####.");
            G('E', "##### #.... #.... ####. #.... #.... #####");
            G('F', "##### #.... #.... ####. #.... #.... #....");
            G('G', ".###. #...# #.... #.### #...# #...# .####");
            G('H', "#...# #...# #...# ##### #...# #...# #...#");
            G('I', ".###. ..#.. ..#.. ..#.. ..#.. ..#.. .###.");
            G('J', "..### ...#. ...#. ...#. ...#. #..#. .##..");
            G('K', "#...# #..#. #.#.. ##... #.#.. #..#. #...#");
            G('L', "#.... #.... #.... #.... #.... #.... #####");
            G('M', "#...# ##.## #.#.# #.#.# #...# #...# #...#");
            G('N', "#...# #...# ##..# #.#.# #..## #...# #...#");
            G('O', ".###. #...# #...# #...# #...# #...# .###.");
            G('P', "####. #...# #...# ####. #.... #.... #....");
            G('Q', ".###. #...# #...# #...# #.#.# #..#. .##.#");
            G('R', "####. #...# #...# ####. #.#.. #..#. #...#");
            G('S', ".#### #.... #.... .###. ....# ....# ####.");
            G('T', "##### ..#.. ..#.. ..#.. ..#.. ..#.. ..#..");
            G('U', "#...# #...# #...# #...# #...# #...# .###.");
            G('V', "#...# #...# #...# #...# #...# .#.#. ..#..");
            G('W', "#...# #...# #...# #.#.# #.#.# #.#.# .#.#.");
            G('X', "#...# #...# .#.#. ..#.. .#.#. #...# #...#");
            G('Y', "#...# #...# .#.#. ..#.. ..#.. ..#.. ..#..");
            G('Z', "##### ....# ...#. ..#.. .#... #.... #####");
            G('0', ".###. #...# #..## #.#.# ##..# #...# .###.");
            G('1', "..#.. .##.. ..#.. ..#.. ..#.. ..#.. .###.");
            G('2', ".###. #...# ....# ...#. ..#.. .#... #####");
            G('3', "####. ....# ....# .###. ....# ....# ####.");
            G('4', "...#. ..##. .#.#. #..#. ##### ...#. ...#.");
            G('5', "##### #.... ####. ....# ....# #...# .###.");
            G('6', ".###. #.... #.... ####. #...# #...# .###.");
            G('7', "##### ....# ...#. ..#.. .#... .#... .#...");
            G('8', ".###. #...# #...# .###. #...# #...# .###.");
            G('9', ".###. #...# #...# .#### ....# ....# .###.");
            G('.', "..... ..... ..... ..... ..... .##.. .##..");
            G(',', "..... ..... ..... ..... .##.. ..#.. .#...");
            G(':', "..... .##.. .##.. ..... .##.. .##.. .....");
            G(';', "..... .##.. .##.. ..... .##.. ..#.. .#...");
            G('!', "..#.. ..#.. ..#.. ..#.. ..#.. ..... ..#..");
            G('?', ".###. #...# ....# ...#. ..#.. ..... ..#..");
            G('-', "..... ..... ..... ##### ..... ..... .....");
            G('+', "..... ..#.. ..#.. ##### ..#.. ..#.. .....");
            G('=', "..... ..... ##### ..... ##### ..... .....");
            G('/', "....# ....# ...#. ..#.. .#... #.... #....");
            G('\'', "..#.. ..#.. .#... ..... ..... ..... .....");
            G('"', ".#.#. .#.#. ..... ..... ..... ..... .....");
            G('(', "...#. ..#.. .#... .#... .#... ..#.. ...#.");
            G(')', ".#... ..#.. ...#. ...#. ...#. ..#.. .#...");
            G('<', "...#. ..#.. .#... #.... .#... ..#.. ...#.");
            G('>', ".#... ..#.. ...#. ....# ...#. ..#.. .#...");
            G('%', "##..# ##..# ...#. ..#.. .#... #..## #..##");
            G('&', ".##.. #..#. #.#.. .#... #.#.# #..#. .##.#");
            G('#', ".#.#. .#.#. ##### .#.#. ##### .#.#. .#.#.");
            G('_', "..... ..... ..... ..... ..... ..... #####");
            G('*', "..... #.#.# .###. ##### .###. #.#.# .....");
            G('·', "..... ..... ..... ..#.. ..... ..... .....");
            G('→', "..... ..#.. ...#. ##### ...#. ..#.. .....");
            G('←', "..... ..#.. .#... ##### .#... ..#.. .....");
            G('↑', "..#.. .###. #.#.# ..#.. ..#.. ..#.. ..#..");
            G('↓', "..#.. ..#.. ..#.. ..#.. #.#.# .###. ..#..");
            return d;
        }
    }
}
