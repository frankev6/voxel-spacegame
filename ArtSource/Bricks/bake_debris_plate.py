"""Bake a neutral hull-plate swatch for the debris particles (QA-001).

Owner: "black broken off blocks, its not that they are lighting dark, look at the screenshot, they are literally black, no
texture, no uv map, just a smooth black cube shot off the hull". The debris VFX draws a cube per broken cell; this gives each
face a 3 m crop of the same look-book ark plating the hull uses (plates, seams, bolts, stencils, wear, cavity grime), in
neutral grey so the particle's palette colour tints it. Own work: generated by our numpy plating generator.

Run with any Python 3 that has numpy (Blender's bundled one works):
    /Applications/Blender.app/Contents/Resources/<ver>/python/bin/python3 ArtSource/Bricks/bake_debris_plate.py

Writes Assets/Game/Art/Nocturne/Plating/DebrisPlate_Albedo.png (sRGB) and DebrisPlate_Normal.png (tangent space), 256 px.
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bake_plating  # noqa: E402

CROP = 512                                  # of the 1024 px, 6 m tile: 3 m of plating per cube face
OUT_PX = 256


def main():
    A, B, N = bake_plating.bake("ark", 0)   # 8-bit, rows top to bottom
    a, b, n = (m[:CROP, :CROP].astype(np.float32) / 255 for m in (A, B, N))

    def down(x):                            # 2x2 box filter
        return x.reshape(OUT_PX, 2, OUT_PX, 2, -1).mean(axis=(1, 3))

    a, b, n = down(a), down(b), down(n)
    # The brick shader's composition (NocturnePlating) on a neutral paint: calm tint, black stencils, dark metal, bright
    # edge wear, seam grime.
    c = 0.80 * (1 + (a[..., 0] * 2 - 0.955) * 0.45)
    c = c + (0.55 - c) * a[..., 3] * 0.6                    # accent stripes read as a mid tone without team colour
    c = c + (0.05 - c) * a[..., 2]
    c = c + (0.28 - c) * b[..., 1] * 0.7
    c = c + (0.95 - c) * b[..., 2] * 0.8
    c = c * (0.35 + 0.65 * n[..., 2])
    albedo = np.stack([c * 1.0, c * 0.99, c * 0.96, np.ones_like(c)], axis=-1)
    nx, ny = n[..., 0] * 2 - 1, n[..., 1] * 2 - 1
    nz = np.sqrt(np.clip(1 - nx * nx - ny * ny, 0, 1))
    normal = np.stack([n[..., 0], n[..., 1], nz * 0.5 + 0.5, np.ones_like(c)], axis=-1)
    for name, img in (("DebrisPlate_Albedo.png", albedo), ("DebrisPlate_Normal.png", normal)):
        path = os.path.join(bake_plating.OUT, name)
        bake_plating.write_png(path, bake_plating.to8(img))
        print("wrote", path, img.shape)


if __name__ == "__main__":
    main()
