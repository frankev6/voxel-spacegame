"""DEV-023 option E, the Hollow: from hollow/hollow_layout.json (hollow_export.py) to what the game builds.

Writes hollow/hollow_blocks.bin, read by Game/Content/Build Hollow (Assets/Game/Editor/Content/HollowBuilder.cs), and
Assets/Game/App/DevRuntime/Playground/HollowLayout.g.cs, the runtime layout (where each piece spawns, the forts, guns, lights,
neon, signs, stations, moored ships, traffic routes, gunships, the wayfinding waypoints and paths, and the cutaway mask).

bin: "HOLW", int32 version 1, int32 piece count; per piece: id and name (int16 length + UTF-8), int32 block count, blocks as
int16 i, j, k, byte side, byte colour, byte material (0 rock, 1 hull, 2 trim); int32 gun count, guns as int16 i, j, k, byte big,
byte orient (0, 4, 8, 12: facing +z, +x, -z, -x). Little-endian.
"""
import json
import math
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "hollow", "hollow_layout.json")
BIN = os.path.join(HERE, "hollow", "hollow_blocks.bin")
CS = os.path.join(ROOT, "Assets", "Game", "App", "DevRuntime", "Playground", "HollowLayout.g.cs")
LAYER = {"low": "Low", "high": "High", "struct": "Struct", "fort": "Fort"}


def s(text):
    b = text.encode("utf-8")
    return struct.pack("<h", len(b)) + b


def orient_of(yaw):
    q = int(round(yaw / (math.pi / 2))) % 4
    return (0, 4, 8, 12)[q]


def f(v):
    return f"{float(v):.2f}f".replace(".00f", "f")


def col(hex_):
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return f"new Color({r:.3f}f, {g:.3f}f, {b:.3f}f)"


def q(text):
    return json.dumps(text)


def main():
    d = json.load(open(SRC))
    cell = d.get("cell", 2.0)
    forts = d.get("forts", [])
    guns_by_fort = {}
    for g in d.get("guns", []):
        if g.get("fort", -1) >= 0:
            guns_by_fort.setdefault(g["fort"], []).append(g)

    out = bytearray(b"HOLW" + struct.pack("<ii", 1, len(d["pieces"])))
    pieces = []
    for p in d["pieces"]:
        ox, oy, oz = p["origin"]
        if abs(oy) > 1e-6:
            sys.exit(f"{p['id']}: origin y must be 0")
        out += s(p["id"]) + s(p.get("name", p["id"]))
        out += struct.pack("<i", len(p["blocks"]))
        for i, j, k, side, c, m in p["blocks"]:
            out += struct.pack("<hhhBBB", i, j, k, side, c, m)
        fort = p.get("fort", -1)
        mounts = []
        if p.get("layer") == "fort" and fort >= 0:
            for g in guns_by_fort.get(fort, []):
                # the gun's cell in the fort grid (pivot = the piece origin = the fort centre), its kit on the flight plane
                mounts.append((int(math.floor((g["x"] - ox) / cell)), 0, int(math.floor((g["z"] - oz) / cell)), 1 if g.get("big") else 0,
                               orient_of(g.get("yaw", 0.0))))
        out += struct.pack("<i", len(mounts))
        for i, j, k, big, o in mounts:
            out += struct.pack("<hhhBB", i, j, k, big, o)
        pieces.append((p["id"], ox, oz, LAYER[p.get("layer", "struct")], fort))
    open(BIN, "wb").write(bytes(out))

    L = []
    w = L.append
    w("// <auto-generated> ArtSource/Hub/hollow_codegen.py from ArtSource/Hub/hollow/hollow_layout.json. Do not edit by hand. </auto-generated>")
    w("#if UNITY_EDITOR || DEVELOPMENT_BUILD")
    w("using Unity.Mathematics;")
    w("using UnityEngine;")
    w("")
    w("namespace Game.App.DevRuntime.Playground")
    w("{")
    w("    internal static partial class HollowLayout")
    w("    {")
    sp = d["spawn"]
    w(f"        internal static readonly float2 Spawn = new float2({f(sp['x'])}, {f(sp['z'])});")
    w(f"        internal const float SpawnYaw = {f(sp.get('yaw', 0))};")
    b = d.get("bounds", [0, 0, 0, 0])
    w(f"        internal static readonly float4 Bounds = new float4({f(b[0])}, {f(b[1])}, {f(b[2])}, {f(b[3])});")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Piece[] Pieces =")
    w("        {")
    for pid, ox, oz, layer, fort in pieces:
        w(f"            new Piece({q(pid)}, new float2({f(ox)}, {f(oz)}), Layer.{layer}, {fort}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Fort[] Forts =")
    w("        {")
    for k, ft in enumerate(forts):
        w(f"            new Fort(new float2({f(ft['x'])}, {f(ft['z'])}), {f(math.radians(ft.get('rate', 0)))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Gun[] Guns =")
    w("        {")
    for g in d.get("guns", []):
        if g.get("fort", -1) >= 0:
            continue
        w(f"            new Gun(new float2({f(g['x'])}, {f(g['z'])}), {f(g.get('yaw', 0))}, {str(bool(g.get('big'))).lower()}, {q(g.get('group', 'edge'))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Light[] Lights =")
    w("        {")
    for li in d.get("lights", []):
        w(f"            new Light(new float3({f(li['x'])}, {f(li['y'])}, {f(li['z'])}), {col(li['col'])}, {f(li.get('r', 3))}, {q(li.get('kind', 'lamp'))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Neon[] Neons =")
    w("        {")
    for n in d.get("neon", []):
        w(f"            new Neon(new float2({f(n['ax'])}, {f(n['az'])}), new float2({f(n['bx'])}, {f(n['bz'])}), {f(n.get('y', 0))}, {col(n['col'])}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Sign[] Signs =")
    w("        {")
    for sg in d.get("signs", []):
        w(f"            new Sign({q(sg['text'])}, new float3({f(sg['x'])}, {f(sg.get('y', 0))}, {f(sg['z'])}), {f(sg.get('yaw', 0))}, {col(sg.get('col', '#FFB347'))}, {f(sg.get('size', 1))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Station[] Stations =")
    w("        {")
    for st in d.get("stations", []):
        w(f"            new Station({q(st['id'])}, StationKind.{st['kind'].capitalize()}, new float2({f(st['x'])}, {f(st['z'])}), {f(st.get('yaw', 0))}, {q(st.get('title', st['id']).upper())}, {q(st.get('merchant', ''))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Moored[] Moorings =")
    w("        {")
    for m in d.get("moored", []):
        w(f"            new Moored({q(m['blueprint'])}, new float2({f(m['x'])}, {f(m['z'])}), {f(m.get('yaw', 0))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Route[] Traffic =")
    w("        {")
    for t in d.get("traffic", []):
        pts = ", ".join(f"new float2({f(x)}, {f(z)})" for x, z in t["route"])
        w(f"            new Route({q(t['blueprint'])}, new[] {{ {pts} }}, {str(bool(t.get('loop'))).lower()}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Guard[] Gunships =")
    w("        {")
    for g in d.get("gunships", []):
        w(f"            new Guard({q(g['blueprint'])}, new float2({f(g['x'])}, {f(g['z'])}), {f(g.get('radius', 150))}),")
    w("        };")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Beacon[] Beacons =")
    w("        {")
    for be in d.get("beacons", []):
        w(f"            new Beacon(new float2({f(be['x'])}, {f(be['z'])}), {col(be.get('col', '#FFB347'))}),")
    w("        };")
    w("        // the approach field: lumpy rocks, each the nearest of the four boulder blueprints by radius (10, 20, 30, 44 m)")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Boulder[] Boulders =")
    w("        {")
    for k, bo in enumerate(d.get("boulders", [])):
        size = min(range(4), key=lambda i: abs((10, 20, 30, 44)[i] - bo["r"]))
        w(f"            new Boulder(new float2({f(bo['x'])}, {f(bo['z'])}), {size}, {f((k * 2.399963) % 6.283185)}),")
    w("        };")
    # wayfinding: at each junction, tunnel mouth and the Maw's entrance, the heading (yaw) of the first leg toward each station
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly Waypoint[] Waypoints =")
    w("        {")
    for wp in d.get("waypoints", []):
        ids = list(wp["to"])
        w(f"            new Waypoint(new float2({f(wp['x'])}, {f(wp['z'])}), new[] {{ {', '.join(q(i) for i in ids)} }}, "
          f"new[] {{ {', '.join(f(wp['to'][i]) for i in ids)} }}),")
    w("        };")
    # each station's shortest flight-band path from the Maw's entrance, a point every ~20 m
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly (string Station, float2[] Points)[] Paths =")
    w("        {")
    for sid, pts in d.get("paths", {}).items():
        w(f"            ({q(sid)}, new[] {{ {', '.join(f'new float2({f(x)}, {f(z)})' for x, z in pts)} }}),")
    w("        };")
    ins = d["inside"]
    w(f"        internal const float InsideCell = {f(ins['cell'])}, InsideX0 = {f(ins['x0'])}, InsideZ0 = {f(ins['z0'])};")
    w(f"        internal const int InsideW = {ins['w']}, InsideH = {ins['h']};")
    w("        [Game.Core.StaticStateOk(\"generated layout\")] internal static readonly string[] InsideRows =")
    w("        {")
    for r in ins["rows"]:
        w(f"            \"{r}\",")
    w("        };")
    w("    }")
    w("}")
    w("#endif")
    open(CS, "w").write("\n".join(L) + "\n")
    cells = sum(sum(bl[3] ** 3 for bl in p["blocks"]) for p in d["pieces"])
    print(f"{len(pieces)} pieces, {cells} cells, bin {len(out) / 1e6:.2f} MB -> {BIN}\n{CS}")


if __name__ == "__main__":
    main()
