#!/usr/bin/env python3
"""Export the direction token sheets as CSS for the HTML design board (SPEC-80 ART-002, used by ART-005).

Python 3 standard library only (SPEC-80 §4.6). After ART-014 reads the frozen original sheets in
docs/design/board/source-tokens/ (runtime Directions/ before that snapshot) and writes
docs/design/board/tokens/<direction>.css. Colour, space, radius, border, text-size and duration tokens are copied as-is.
Font tokens become Google Fonts families (table below) plus -weight and -stretch companions. Each file starts with the
Google Fonts @import for its families (fonts.googleapis.com is one of the board's two allowed external hosts) and scopes
its tokens to [data-direction="<direction>"], so the board can show several directions side by side.

  export_board_tokens.py           writes all directions
  export_board_tokens.py --check   exit 1 if a written file differs from what would be generated (for check_art_docs board)
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_tokens import THEME, ROOT, REFERENCE_THEME, parse_sheet  # noqa: E402

OUT_DIR = os.path.join(ROOT, "docs", "design", "board", "tokens")
COPIED = re.compile(r"^--(color|space|radius|border|text|duration)-")
FONT_TOKENS = ["--font-display", "--font-body", "--font-body-strong", "--font-mono"]

# FontAsset file stem → (CSS family stack, weight, stretch %, Google Fonts family or None)
FONTS = {
    "FNT_BarlowCondensed-SemiBold": ("'Barlow Condensed', system-ui, sans-serif", 600, 100, "Barlow Condensed"),
    "FNT_Barlow-Regular": ("'Barlow', system-ui, sans-serif", 400, 100, "Barlow"),
    "FNT_Barlow-SemiBold": ("'Barlow', system-ui, sans-serif", 600, 100, "Barlow"),
    "FNT_IBMPlexMono-Regular": ("'IBM Plex Mono', ui-monospace, monospace", 400, 100, "IBM Plex Mono"),
    "FNT_Michroma-Regular": ("'Michroma', system-ui, sans-serif", 400, 100, "Michroma"),
    "FNT_Inter-Regular": ("'Inter', system-ui, sans-serif", 400, 100, "Inter"),
    "FNT_Inter-SemiBold": ("'Inter', system-ui, sans-serif", 600, 100, "Inter"),
    "FNT_JetBrainsMono-Regular": ("'JetBrains Mono', ui-monospace, monospace", 400, 100, "JetBrains Mono"),
    "FNT_ArchivoExpanded-ExtraBold": ("'Archivo', system-ui, sans-serif", 800, 125, "Archivo"),
    "FNT_AtkinsonHyperlegible-Regular": ("'Atkinson Hyperlegible', system-ui, sans-serif", 400, 100, "Atkinson Hyperlegible"),
    "FNT_AtkinsonHyperlegible-Bold": ("'Atkinson Hyperlegible', system-ui, sans-serif", 700, 100, "Atkinson Hyperlegible"),
    "FNT_SpaceMono-Regular": ("'Space Mono', ui-monospace, monospace", 400, 100, "Space Mono"),
    "OfficeCodePro-Regular": ("'Office Code Pro', ui-monospace, monospace", 400, 100, None),   # placeholder, not on Google Fonts
    "OfficeCodePro-Bold": ("'Office Code Pro', ui-monospace, monospace", 700, 100, None),
}


def font_stem(value):
    m = re.search(r'/([^/"]+)_SDF\.asset"\)', value)
    if not m or m.group(1) not in FONTS:
        raise SystemExit(f"export_board_tokens: no Google Fonts mapping for font value {value!r}; add it to FONTS")
    return m.group(1)


def google_fonts_import(stems):
    families = {}
    for stem in stems:
        _, weight, stretch, family = FONTS[stem]
        if family:
            families.setdefault(family, set()).add((stretch, weight))
    if not families:
        return ""
    parts = []
    for family in sorted(families):
        axes = sorted(families[family])
        name = family.replace(" ", "+")
        if any(s != 100 for s, _ in axes):
            parts.append(f"family={name}:wdth,wght@" + ";".join(f"{s},{w}" for s, w in axes))
        else:
            parts.append(f"family={name}:wght@" + ";".join(str(w) for w in sorted({w for _, w in axes})))
    return f'@import url("https://fonts.googleapis.com/css2?{"&".join(parts)}&display=swap");\n'


def render(direction, values):
    stems = [font_stem(values[t]) for t in FONT_TOKENS if t in values]
    lines = [f"/* Generated by tools/art/export_board_tokens.py from Assets/Game/UI/Theme/Directions/tokens-{direction}.uss."
             " Do not edit. */",
             google_fonts_import(stems).rstrip("\n"),
             f'[data-direction="{direction}"] {{']
    for name, value in values.items():
        if COPIED.match(name):
            lines.append(f"    {name}: {value};")
    for name in FONT_TOKENS:
        if name in values:
            family, weight, stretch, _ = FONTS[font_stem(values[name])]
            lines += [f"    {name}: {family};", f"    {name}-weight: {weight};", f"    {name}-stretch: {stretch}%;"]
    lines.append("}")
    return "\n".join(l for l in lines if l) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    args = ap.parse_args(argv)
    sheets = sorted(glob.glob(os.path.join(REFERENCE_THEME, "tokens-*.uss")))
    if not sheets:  # ART-002 before the ART-014 reference snapshot
        sheets = sorted(glob.glob(os.path.join(THEME, "Directions", "tokens-*.uss")))
    if not sheets:
        raise SystemExit("export_board_tokens: no direction sheets found")
    stale = []
    for sheet in sheets:
        direction = re.fullmatch(r"tokens-([a-z0-9-]+)\.uss", os.path.basename(sheet)).group(1)
        values, _ = parse_sheet(sheet)
        text = render(direction, values)
        out = os.path.join(OUT_DIR, f"{direction}.css")
        if args.check:
            current = open(out, encoding="utf-8").read() if os.path.exists(out) else None
            if current != text:
                stale.append(os.path.relpath(out, ROOT))
            continue
        os.makedirs(OUT_DIR, exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"export_board_tokens: wrote {os.path.relpath(out, ROOT)}")
    for path in stale:
        print(f"ERROR {path} is out of date; run tools/art/export_board_tokens.py")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
